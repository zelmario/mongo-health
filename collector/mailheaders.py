"""The headers that decide whether an email arrives at all.

Everything this product produces leaves by email. If it lands in spam the customer sees nothing
and concludes the tool found nothing — the same failure that has bitten this project twice
already, where silence was indistinguishable from good news.

Most of what governs that is DNS and belongs to whoever owns the domain (see
`deploy/mail-dns.md`). What belongs here is the small set of headers a filter reads to decide
whether an automated message is a legitimate service or a stranger:

  Message-ID        Must be at the domain that sent it. Python invents one from the local
                    hostname when it is missing, so a message from `collector@example.com`
                    went out identifying itself as coming from `dbhost` — a mismatch that
                    costs reputation for no reason at all.
  Date              Required by RFC 5322. `send_message` adds it, but the outbox path writes
                    the bytes directly and produced messages without one.
  Auto-Submitted    RFC 3834. Says "generated by a machine, do not reply to this automatically",
                    which is what stops a customer's out-of-office reply from arriving back and,
                    in the worst case, looping.
  List-Unsubscribe  The single header modern filters most want to see on recurring mail. It is
                    also the honest thing: an alert somebody cannot turn off is the noise that
                    ends subscriptions, and this product's whole argument is that it stays
                    quiet.

Deliberately not here: anything that pretends. No fake `Precedence: bulk`, no invented
`X-Mailer`. Headers that claim more than is true are exactly what filters are built to notice.
"""
from __future__ import annotations

from email.headerregistry import Address
from email.message import EmailMessage
from email.utils import formatdate, make_msgid, parseaddr


def sender_domain(sender: str, fallback: str = "localhost") -> str:
    """The domain a message is actually from, out of a `Name <box@domain>` string.

    Everything else in this module keys off it, and getting it from the configured sender
    rather than from a constant means a self-hosted install sending as its own domain is
    consistent without editing code.
    """
    _, address = parseaddr(sender)
    if "@" not in address:
        return fallback
    domain = address.rsplit("@", 1)[1].strip()
    return domain or fallback


def stamp(message: EmailMessage, sender: str, unsubscribe: str | None = None) -> EmailMessage:
    """Add the headers that should be on every message this product sends.

    Idempotent and never overwrites: a caller that already set something meant it.
    """
    domain = sender_domain(sender)

    if "Message-ID" not in message:
        message["Message-ID"] = make_msgid(domain=domain)
    if "Date" not in message:
        message["Date"] = formatdate(localtime=True)
    if "Auto-Submitted" not in message:
        message["Auto-Submitted"] = "auto-generated"

    if unsubscribe and "List-Unsubscribe" not in message:
        # A mailto rather than a URL, on purpose. One-click unsubscribe wants an HTTPS endpoint
        # that acts on an unauthenticated POST, and half-building that -- a link that looks
        # like it stops the mail and does not -- is worse than not offering it. The address is
        # a real inbox somebody reads, which is the older and slower promise, honestly made.
        message["List-Unsubscribe"] = f"<mailto:{unsubscribe}>"
    return message
