"""The guard that notices the collector stopped.

This is the last thing standing between you and a service that quietly died. Everything
else in the system reports on clusters; this reports on the reporter, and it is deliberately
built to keep working when the rest does not — it reads state files and the clock, nothing else.

So the tests care about two things: that it never stays quiet when it should speak, and that
its exit code is honest, because a cron entry's own mail is the net underneath it.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from watchdog import STALE_AFTER_HOURS, check, compose  # noqa: E402

NOW = datetime(2026, 8, 9, 12, 0, tzinfo=timezone.utc)


def cluster(tmp: Path, name="prod", last_capture=None, raw: str | None = None) -> Path:
    base = tmp / name
    base.mkdir(parents=True, exist_ok=True)
    if raw is not None:
        (base / "state.json").write_text(raw)
    else:
        (base / "state.json").write_text(json.dumps({
            "cluster_id": name,
            "last_capture": last_capture, "files": {}}))
    return base


def ago(**kw) -> str:
    return (NOW - timedelta(**kw)).isoformat()


# ------------------------------------------------------------------- when it must stay quiet

def test_a_recent_capture_raises_nothing(tmp_path: Path):
    cluster(tmp_path, last_capture=ago(hours=1))
    assert check(tmp_path, NOW, STALE_AFTER_HOURS) == []


def test_a_few_missed_runs_are_tolerated(tmp_path: Path):
    """A slow Atlas job or a long first capture is not a dead collector."""
    cluster(tmp_path, last_capture=ago(hours=3))
    assert check(tmp_path, NOW, STALE_AFTER_HOURS) == []


# ---------------------------------------------------------------------- when it must speak

def test_a_morning_of_silence_raises_the_alarm(tmp_path: Path):
    cluster(tmp_path, last_capture=ago(hours=5))
    problems = check(tmp_path, NOW, STALE_AFTER_HOURS)
    assert len(problems) == 1
    assert "no new data for 5 h" in problems[0]["why"]


def test_a_cluster_that_never_captured_is_reported_differently(tmp_path: Path):
    """"Never started" and "stopped" have different causes and different fixes."""
    cluster(tmp_path, last_capture=None)
    assert check(tmp_path, NOW, STALE_AFTER_HOURS)[0]["why"] == "never captured"


def test_an_unreadable_state_file_is_an_alarm_not_a_skip(tmp_path: Path):
    """Corruption must not be silently stepped over.

    A cluster whose state cannot be read is a cluster nobody can prove is being collected.
    """
    cluster(tmp_path, raw="{ this is not json")
    problems = check(tmp_path, NOW, STALE_AFTER_HOURS)
    assert len(problems) == 1 and "unreadable" in problems[0]["why"]


def test_every_stopped_cluster_is_listed(tmp_path: Path):
    cluster(tmp_path, name="a", last_capture=ago(hours=20))
    cluster(tmp_path, name="b", last_capture=ago(hours=30))
    cluster(tmp_path, name="c", last_capture=ago(minutes=5))
    problems = check(tmp_path, NOW, STALE_AFTER_HOURS)
    assert {p["cluster"] for p in problems} == {"a", "b"}


def test_the_worst_offender_comes_first(tmp_path: Path):
    """Whoever reads the alert should see the longest silence at the top."""
    cluster(tmp_path, name="recent", last_capture=ago(hours=16))
    cluster(tmp_path, name="ancient", last_capture=ago(days=5))
    assert check(tmp_path, NOW, STALE_AFTER_HOURS)[0]["cluster"] == "ancient"


def test_the_threshold_is_configurable(tmp_path: Path):
    """A tighter schedule needs a tighter alarm."""
    cluster(tmp_path, last_capture=ago(hours=3))
    assert check(tmp_path, NOW, 2) != []
    assert check(tmp_path, NOW, 6) == []


# ------------------------------------------------------------------------------ the alert

def test_the_alert_separates_the_collector_from_the_clusters(tmp_path: Path):
    """The clusters may be perfectly healthy. What stopped is the watching.

    Conflating the two would send somebody to debug a database that is fine.
    """
    problems = [{"cluster": "prod", "hours": 20.0,
                 "why": "last capture 20 h ago"}]
    body = compose(problems, ["ops@x"], "c@x", NOW).get_content()
    assert "not about the clusters themselves" in body


def test_the_alert_says_the_status_page_is_stale(tmp_path: Path):
    """Because the page is generated by the collector, it is still showing the last good run.

    Whoever reads this must not be reassured by looking at it.
    """
    problems = [{"cluster": "prod", "hours": 20.0, "why": "x"}]
    assert "last run" in compose(problems, ["ops@x"], "c@x", NOW).get_content()


def test_the_alert_names_every_affected_cluster(tmp_path: Path):
    problems = [{"cluster": f"c{i}", "hours": 20.0, "why": "x"}
                for i in range(3)]
    body = compose(problems, ["ops@x"], "c@x", NOW).get_content()
    assert all(f"c{i}" in body for i in range(3))


def test_a_single_failure_is_named_in_the_subject(tmp_path: Path):
    problems = [{"cluster": "prod", "hours": 20.0, "why": "x"}]
    assert "prod" in compose(problems, ["ops@x"], "c@x", NOW)["Subject"]


def test_the_alert_carries_where_to_look(tmp_path: Path):
    """An alarm without a next step gets acknowledged and forgotten."""
    problems = [{"cluster": "prod", "hours": 20.0, "why": "x"}]
    body = compose(problems, ["ops@x"], "c@x", NOW).get_content()
    assert "cron" in body and "API key" in body


# --------------------------------------------------------------- what is not being watched

def roster(tmp: Path, *names: str) -> None:
    (tmp / "roster.json").write_text(json.dumps({
        "written_at": NOW.isoformat(),
        "clusters": [{"cluster_id": n} for n in names],
    }))


def test_a_paused_cluster_stops_being_alarming(tmp_path: Path):
    """Pausing is a row in Postgres and this program never reads Postgres.

    Without the roster all it could see was a state file that stopped moving, which is exactly
    what a broken collector looks like — so it alerted for four days about a cluster somebody
    had switched off on purpose.
    """
    cluster(tmp_path, name="watched", last_capture=ago(hours=1))
    cluster(tmp_path, name="paused", last_capture=ago(days=4))
    roster(tmp_path, "watched")

    assert check(tmp_path, NOW, STALE_AFTER_HOURS) == []


def test_a_cluster_on_the_roster_is_still_judged(tmp_path: Path):
    """The roster narrows what is watched; it does not excuse what is."""
    cluster(tmp_path, name="prod", last_capture=ago(days=4))
    roster(tmp_path, "prod")

    problems = check(tmp_path, NOW, STALE_AFTER_HOURS)
    assert [p["cluster"] for p in problems] == ["prod"]


def test_no_roster_means_watch_everything(tmp_path: Path):
    """A self-hosted install has a config file, no database, and nothing that can pause.

    Absence must not be read as an empty list, or the watchdog goes quiet on exactly the
    deployment that has nothing else watching it.
    """
    cluster(tmp_path, name="prod", last_capture=ago(days=4))
    assert len(check(tmp_path, NOW, STALE_AFTER_HOURS)) == 1


def test_a_corrupt_roster_does_not_silence_the_watchdog(tmp_path: Path):
    """Failing open, on purpose. This program exists to work when other things are broken.

    Read strictly, a truncated roster would mean "nothing is being watched" and every real
    outage would go unreported because of one bad JSON file.
    """
    cluster(tmp_path, name="prod", last_capture=ago(days=4))
    (tmp_path / "roster.json").write_text('{"clusters": [{"cluster_id": "pro')

    assert len(check(tmp_path, NOW, STALE_AFTER_HOURS)) == 1


# ------------------------------------------------------------------- the all-clear

import watchdog  # noqa: E402

SMTP = {"host": "localhost", "port": 1025, "from": "Collector <collector@example.com>"}


def entry(name="prod", kind="atlas") -> dict:
    """A roster line the way `capture.write_roster` writes it."""
    return {"cluster_id": name, "source_kind": kind}


def owner_roster(tmp: Path, *entries: dict) -> None:
    (tmp / "roster.json").write_text(json.dumps({
        "written_at": NOW.isoformat(), "clusters": list(entries)}))


def outbox(monkeypatch) -> list:
    """Every message that would have left, without an SMTP server in the tests."""
    box = []
    monkeypatch.setattr(watchdog, "send", lambda msg, smtp: box.append(msg))
    return box


def test_the_all_clear_counts_only_what_is_watched(tmp_path, monkeypatch, capsys):
    """Regression: the roster became a mapping and this line intersected a set with a dict,
    which crashed the run on every healthy cluster. Found by running it, not by a test."""
    # `main` reads the real clock, so the freshness has to be real too -- everything else in
    # this file is frozen at NOW and would read as eleven days of silence.
    real_now = datetime.now(timezone.utc)
    cluster(tmp_path, name="prod", last_capture=(real_now - timedelta(hours=1)).isoformat())
    cluster(tmp_path, name="paused", last_capture=ago(days=9))
    owner_roster(tmp_path, entry())
    monkeypatch.setattr(sys, "argv", ["watchdog", "--data", str(tmp_path),
                                      "--config", str(tmp_path / "absent.json")])

    assert watchdog.main() == 0
    out = capsys.readouterr().out
    assert "all 1 cluster(s)" in out and "1 paused" in out


# ------------------------------------------------- when we are looking at a dead source

def with_arrivals(tmp: Path, name: str, ran: str, arrived: str | None, kind="directory") -> None:
    base = tmp / name
    base.mkdir(parents=True, exist_ok=True)
    (base / "state.json").write_text(json.dumps({
        "cluster_id": name, "source_kind": kind,
        "last_capture": ran, "last_new_data": arrived, "files": {}}))


def test_a_dead_source_is_caught_while_capture_keeps_running(tmp_path: Path):
    """The failure that went unnoticed for a day on a real cluster.

    The local replica set behind `rs-local` stopped on 19/08. Capture went on running every
    hour and finding nothing, `last_capture` moved every hour with it, the alert stayed quiet,
    and the page went on saying "4.9 days watched". Nobody was watching that cluster and
    nothing anywhere said so.
    """
    with_arrivals(tmp_path, "rs-local", ran=ago(minutes=10), arrived=ago(hours=29))

    problems = check(tmp_path, NOW, STALE_AFTER_HOURS)

    assert len(problems) == 1
    assert "no new data for 29 h" in problems[0]["why"]
    assert "the source stopped" in problems[0]["why"], "it says which end went quiet"


def test_a_source_that_is_alive_says_nothing(tmp_path: Path):
    with_arrivals(tmp_path, "rs-local", ran=ago(minutes=10), arrived=ago(minutes=40))
    assert check(tmp_path, NOW, STALE_AFTER_HOURS) == []


def test_the_collector_being_down_still_says_so(tmp_path: Path):
    """Both ends quiet. The operator reads this one and it must not blame the source."""
    with_arrivals(tmp_path, "prod", ran=ago(hours=9), arrived=ago(hours=9), kind="atlas")

    why = check(tmp_path, NOW, STALE_AFTER_HOURS)[0]["why"]

    assert "capture has not run" in why and "the source stopped" not in why


def test_a_state_written_before_arrivals_were_tracked_uses_what_it_has(tmp_path: Path):
    """An upgrade must not turn every cluster into an alarm, nor into a silence."""
    cluster(tmp_path, name="old", last_capture=ago(minutes=30))
    assert check(tmp_path, NOW, STALE_AFTER_HOURS) == []
    cluster(tmp_path, name="old", last_capture=ago(hours=9))
    assert len(check(tmp_path, NOW, STALE_AFTER_HOURS)) == 1


# ------------------------------------------------------ not saying the same thing every hour

def problem(cluster="prod", last_data="2026-08-19T12:00:00+00:00", hours=9.0) -> dict:
    return {"cluster": cluster, "hours": hours,
            "last_data": last_data, "notify": [], "why": f"no new data for {hours:.0f} h"}


def agree(tmp_path, problems, now) -> bool:
    """Ask, and record the answer the way `main` does when it sends."""
    send, state = watchdog.worth_repeating(tmp_path, problems, now)
    if send:
        watchdog.write_outages(tmp_path, state)
    return send


def test_the_first_alert_always_goes_out(tmp_path):
    assert agree(tmp_path, [problem()], NOW) is True


def test_the_same_outage_is_not_reported_every_hour(tmp_path):
    """It runs hourly and a dead source can last a week. The fourth identical email is already
    being filtered, and the filter does not know to stop at the fifth."""
    agree(tmp_path, [problem()], NOW)

    assert agree(tmp_path, [problem()], NOW + timedelta(hours=1)) is False
    assert agree(tmp_path, [problem()], NOW + timedelta(hours=12)) is False


def test_an_ignored_outage_comes_back_the_next_day(tmp_path):
    """Quiet is not the same as forgotten: nobody acted, and it is still true."""
    agree(tmp_path, [problem()], NOW)
    assert agree(tmp_path, [problem()], NOW + timedelta(hours=25)) is True


def test_a_second_cluster_going_down_is_news_immediately(tmp_path):
    """A different situation, not a reminder of the same one. Waiting a day to mention it would
    hide the shape of the failure — one source dying is not the same as two."""
    agree(tmp_path, [problem()], NOW)

    assert agree(tmp_path, [problem(), problem("stage")], NOW + timedelta(hours=1)) is True


def test_a_cluster_that_recovered_and_stopped_again_is_not_swallowed(tmp_path):
    """Same cluster, same wording, different outage. Comparing names alone would call the
    second one a repeat of the first and say nothing for a day."""
    agree(tmp_path, [problem()], NOW)

    assert agree(tmp_path, [problem(last_data="2026-08-20T06:00:00+00:00")],
                 NOW + timedelta(hours=2)) is True


def test_a_quiet_repeat_still_exits_non_zero(tmp_path, monkeypatch, capsys):
    """The cron's own mail is the net underneath this program. Reporting a clean run because we
    already sent the email would take the net away on exactly the days it is needed."""
    cluster(tmp_path, name="prod", last_capture=ago(hours=9))
    (tmp_path / "config.json").write_text(json.dumps(
        {"smtp": {"host": "localhost", "port": 1025, "operator": "ops@x.test"}}))
    monkeypatch.setattr(watchdog, "send", lambda msg, smtp: None)
    argv = ["watchdog", "--data", str(tmp_path), "--config", str(tmp_path / "config.json"),
            "--send"]
    monkeypatch.setattr(sys, "argv", argv)

    assert watchdog.main() == 1
    monkeypatch.setattr(sys, "argv", argv)
    assert watchdog.main() == 1
    assert "already alerted" in capsys.readouterr().out


def test_without_an_operator_the_alert_goes_to_notify(tmp_path, monkeypatch):
    """One person running this for their own clusters should not have to name themselves twice."""
    cluster(tmp_path, name="prod", last_capture=ago(hours=9))
    (tmp_path / "config.json").write_text(json.dumps(
        {"notify": ["me@x.test"], "smtp": {"host": "localhost", "port": 1025}, "clusters": []}))
    sent = []
    monkeypatch.setattr(watchdog, "send", lambda msg, smtp: sent.append(msg))
    monkeypatch.setattr(sys, "argv", ["watchdog", "--data", str(tmp_path), "--config",
                                      str(tmp_path / "config.json"), "--send"])
    assert watchdog.main() == 1
    assert [m["To"] for m in sent] == ["me@x.test"]


# ------------------------------------------------------- two copies running at the same time

def test_a_second_watchdog_reports_nothing_while_the_first_holds_the_lock(tmp_path, monkeypatch,
                                                                          capsys):
    """Measured in production, not imagined: two instances started within the same second on
    22/08, systemd catching up runs missed while the machine slept. The only reason nobody was
    emailed twice is that one finished before the other read the state file.
    """
    import fcntl

    cluster(tmp_path, name="prod", last_capture=ago(hours=9))
    (tmp_path / "config.json").write_text(json.dumps(
        {"smtp": {"host": "localhost", "port": 1025, "operator": "ops@x.test"}}))
    box = outbox(monkeypatch)

    # Somebody else is already inside.
    held = (tmp_path / f".{watchdog.NOTIFIED}.lock").open("w")
    fcntl.flock(held, fcntl.LOCK_EX)
    try:
        monkeypatch.setattr(sys, "argv", ["watchdog", "--data", str(tmp_path), "--send",
                                          "--config", str(tmp_path / "config.json")])
        code = watchdog.main()
    finally:
        held.close()

    assert box == [], "the other instance is sending; this one must not"
    assert code == 1, "and it still says something is wrong"
    assert "leaving it to that one" in capsys.readouterr().out


def test_the_lock_is_released_and_the_next_run_reports(tmp_path, monkeypatch):
    """A lock that outlives the process it protected would silence the watchdog for ever, which
    is a worse failure than the one it prevents."""
    cluster(tmp_path, name="prod", last_capture=ago(hours=9))
    (tmp_path / "config.json").write_text(json.dumps(
        {"smtp": {"host": "localhost", "port": 1025, "operator": "ops@x.test"}}))
    box = outbox(monkeypatch)
    argv = ["watchdog", "--data", str(tmp_path), "--send",
            "--config", str(tmp_path / "config.json")]

    monkeypatch.setattr(sys, "argv", argv)
    watchdog.main()
    monkeypatch.setattr(sys, "argv", argv)
    watchdog.main()          # the lock from the first run must be gone

    assert len(box) == 1, "one alert, and the second run was quiet for the right reason"


def test_the_program_runs_when_it_is_run(tmp_path):
    """As a program, not as a module. Everything else here calls `main()` directly, which is
    exactly what let a refactor swallow the `if __name__ == "__main__"` block into the function
    above it: forty-three tests passed while the deployed watchdog silently did nothing on every
    invocation for twenty minutes.
    """
    import subprocess

    cluster(tmp_path, name="prod", last_capture=ago(days=3))
    here = Path(__file__).resolve().parents[1]

    done = subprocess.run(
        [sys.executable, str(here / "watchdog.py"), "--data", str(tmp_path),
         "--config", str(tmp_path / "absent.json")],
        capture_output=True, text=True, timeout=60, cwd=here)

    assert "not capturing" in done.stdout, "it has to actually say something"
    assert done.returncode == 1, "and exit non-zero, which is what the cron reads"
