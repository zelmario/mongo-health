"""The status page, whose single most important job is not to lie.

A page generated by the collector cannot be trusted to report the collector. If cron stops, the
page is never rebuilt and freezes displaying the last healthy run — so the assessment logic has
to be paranoid about exactly one thing: a cluster with no findings whose collector has stopped
is NOT healthy. It is unobserved, and painting it green is the one failure that turns a
monitoring product into a liability.

Most of these tests exist to pin that ordering. The rest check that the two history numbers
stay apart, because conflating them would misstate what the customer is paying for.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from status import (ATLAS_DAYS, assess, build, read_clusters,  # noqa: E402
                    recent_findings, render_retention)

NOW = datetime(2026, 8, 9, 12, 0, tzinfo=timezone.utc)


def ago(**kw) -> str:
    return (NOW - timedelta(**kw)).isoformat()


def cluster(findings=(), last_capture=None, observed=30.0, raw=30.0,
            unresolved=(), empty=False) -> dict:
    return {
        "customer_id": "acme", "cluster_id": "prod",
        "last_capture": last_capture if last_capture is not None else ago(minutes=20),
        "nodes": [{"node": "n0", "hostname": "n0.mongodb.net", "version": "8.0.29",
                   "samples": 86_400, "from": ago(days=raw), "to": ago(minutes=1),
                   "gaps": 0, "seconds_without_data": 0}],
        "days_observed": observed, "days_of_raw_ftdc": raw, "megabytes": 100.0,
        "findings": list(findings), "findings_total": len(findings),
        "rules_evaluated": 14, "rules_unresolved": list(unresolved),
        **({"empty": True} if empty else {}),
    }


def finding(severity="critical", detected=None) -> dict:
    return {"id": "f1", "severity": severity, "title": "Read ticket pool saturated",
            "what": "…", "node": "n0.mongodb.net", "worstFromMs": 1_754_000_000_000,
            "secondsInState": 600, "toMs": 1_754_000_000_000,
            "detected_at": detected or ago(hours=2)}


# ------------------------------------------------- the one thing this page must never get wrong

def test_a_stopped_collector_is_never_healthy():
    """No findings from a collector that stopped is the absence of news, not good news.

    The whole page is generated by the collector, so if this were reported as healthy the
    customer would be looking at a green light produced by something that is not running.
    """
    state, label, note = assess(cluster(last_capture=ago(days=3)), NOW)
    assert state == "stale"
    assert "not capturing" in label.lower()
    assert "collector" in note.lower()


def test_staleness_outranks_findings():
    """Even with a critical finding, "we stopped watching" is the more urgent statement.

    Reporting the finding alone would imply the picture is current, when it is three days old.
    """
    state, _, _ = assess(cluster(findings=[finding()], last_capture=ago(days=3)), NOW)
    assert state == "stale"


def test_a_recent_capture_with_no_findings_is_healthy():
    assert assess(cluster(), NOW)[0] == "healthy"


def test_a_few_missed_runs_are_not_yet_an_alarm():
    """The cron runs hourly. A slow Atlas job or two must not raise the alarm."""
    assert assess(cluster(last_capture=ago(hours=3)), NOW)[0] == "healthy"


def test_a_morning_of_silence_is():
    assert assess(cluster(last_capture=ago(hours=5)), NOW)[0] == "stale"


def test_a_configured_cluster_that_never_captured_says_so():
    """Distinct from "stopped": it never started, and the fix is different."""
    state, label, note = assess(cluster(empty=True), NOW)
    assert state == "empty"
    assert "no data" in label.lower()


def test_severity_of_recent_findings_drives_the_state():
    assert assess(cluster(findings=[finding("critical")]), NOW)[0] == "critical"
    assert assess(cluster(findings=[finding("warning")]), NOW)[0] == "attention"
    assert assess(cluster(findings=[finding("info")]), NOW)[0] == "attention"


def test_old_findings_do_not_keep_a_cluster_red():
    """Last month's incident is history, not current state."""
    old = finding("critical", detected=ago(days=30))
    assert assess(cluster(findings=[old]), NOW)[0] == "healthy"
    assert recent_findings(cluster(findings=[old]), NOW) == []


# ------------------------------------------------------------------- the two history numbers

def test_retention_bar_compares_raw_ftdc_against_atlas():
    """Like for like: what can still be opened, against what Atlas would still be holding."""
    html = render_retention(cluster(raw=30.0, observed=30.0))
    assert "27" in html, "30 days held minus Atlas's 3 is what the customer gained"


def test_a_new_cluster_is_told_it_is_still_inside_the_atlas_window():
    """Honest on day one, and it stops being true within a couple of weeks."""
    html = render_retention(cluster(raw=1.0, observed=1.0))
    assert "still inside" in html


def test_pruned_history_is_shown_separately():
    """After pruning, "watched for" and "can be opened" diverge.

    Showing only the second would understate the service; only the first would overstate
    what can be inspected.
    """
    html = render_retention(cluster(observed=400.0, raw=365.0))
    assert "400" in html and "pruned" in html


def test_no_pruning_note_when_the_numbers_agree():
    """A cluster that has never been pruned must not carry a line explaining pruning."""
    assert "pruned" not in render_retention(cluster(observed=30.0, raw=30.0))


# ------------------------------------------------------------------------------ coverage

def test_unresolved_rules_are_surfaced():
    """Coverage the customer believes they have and do not.

    A rule that cannot resolve its metric looks exactly like one that found nothing, and that
    failure mode has bitten this project repeatedly.
    """
    page = build([cluster(unresolved=[{"id": "flow-control-engaged", "metric": "x"}])], NOW)
    assert "cannot resolve" in page


def test_all_rules_resolving_is_stated_positively():
    page = build([cluster()], NOW)
    assert "14 rules" in page


# ---------------------------------------------------------------------------- reading disk

def test_a_cluster_with_no_summary_still_appears(tmp_path: Path):
    """Configured but never captured is exactly what the customer needs to see.

    Omitting it would make a cluster that was never collected indistinguishable from one that
    does not exist.
    """
    base = tmp_path / "acme" / "prod"
    base.mkdir(parents=True)
    (base / "state.json").write_text(json.dumps(
        {"customer_id": "acme", "cluster_id": "prod", "last_capture": None, "files": {}}))
    found = read_clusters(tmp_path)
    assert len(found) == 1 and found[0].get("empty")


def test_the_page_renders_with_no_clusters_at_all(tmp_path: Path):
    """An empty install must produce a page, not a traceback."""
    assert "No clusters configured" in build([], NOW)
